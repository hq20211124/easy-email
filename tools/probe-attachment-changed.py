"""Attachment-changed probe, part 1: the file on disk, and the probe script that uses it.

`design/07` §5.5: a draft records each attachment's sha256 when it is added, and the send path
compares that against the file. This probe exercises the comparison on a **real** profile, in the two
shapes a user can actually hit:

* **at enqueue** — the recorded hash does not match the file, which is what a file edited *before*
  pressing send looks like;
* **after enqueue** — the hash matched when the message was frozen, and the file changed afterwards,
  which is what the worker's own re-check exists for.

Sub-commands:
    prepare   write the attachment file and generate the probe script with its real hash
    mutate    change the file, so the frozen hash no longer matches
    clean     remove the probe row from the outbox and the attachment file
"""

import hashlib
import os
import sqlite3
import sys

ATTACHMENT = os.path.join(os.environ["TEMP"], "easy-email-probe-attachment.txt")
PROBE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "probe-attachment-changed.mjs")
DB = os.path.join(os.environ["APPDATA"], "com.easyemail.desktop", "user.db")
SUBJECT = "附件被改动探针"

PROBE_TEMPLATE = """/* Generated by this script; the hashes are baked in. */\n/**
 * Attachment-changed probe, generated by `tools/probe-attachment-changed.py` (hashes baked in).
 *
 * Run twice: the first run enqueues, the second reports what the outbox decided.
 */
(async () => {
  const invoke = window.__TAURI__.core.invoke;
  const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
  const phase = globalThis.__attachProbePhase ?? 'enqueue';

  const attachment = {
    name: 'probe.txt',
    mime: 'text/plain',
    path: %(path)s,
    size: %(size)d,
    sha256: %(hash)s,
  };

  if (phase === 'enqueue') {
    const accountId = state.accountId;

    // (1) A hash that cannot match: what pressing send after editing the file looks like.
    let mismatch = null;
    try {
      await invoke('enqueue_send', {
        accountId,
        mail: payload.outgoingMail({
          to: ['me@example.com'],
          cc: [],
          bcc: [],
          subject: '附件被改动探针（应当被拒绝）',
          bodyText: '这条不该入队。',
          bodyHtml: null,
          inReplyTo: null,
          references: [],
          attachments: [{ ...attachment, sha256: '0'.repeat(64) }],
        }),
      });
    } catch (error) {
      mismatch = String(error);
    }

    // (2) The real hash, so the message freezes — and the file is changed right after this returns.
    const id = await invoke('enqueue_send', {
      accountId,
      mail: payload.outgoingMail({
        to: ['me@example.com'],
        cc: [],
        bcc: [],
        subject: %(subject)s,
        bodyText: '这条会在附件被改动后停下。',
        bodyHtml: null,
        inReplyTo: null,
        references: [],
        attachments: [attachment],
      }),
    });

    globalThis.__attachProbePhase = 'report';
    globalThis.__attachProbeId = id;
    return { stage: 'enqueued', mismatch, id };
  }

  // The worker ticks every five seconds and the undo window is five; give both room.
  await wait(14000);
  const rows = await invoke('list_outbox', { accountId: state.accountId });
  const row = rows.find((entry) => entry.id === globalThis.__attachProbeId) ?? null;
  return {
    stage: 'reported',
    row: row && {
      id: row.id,
      state: row.state,
      attempts: row.attempts,
      last_error: row.last_error,
      spool_bytes: row.spool_bytes,
    },
  };
})()
"""


def prepare():
    with open(ATTACHMENT, "w", encoding="utf-8") as handle:
        handle.write("probe attachment, version one\n")
    raw = open(ATTACHMENT, "rb").read()
    digest = hashlib.sha256(raw).hexdigest()

    with open(PROBE, "w", encoding="utf-8") as handle:
        handle.write(
            PROBE_TEMPLATE
            % {
                "path": '"%s"' % ATTACHMENT.replace("\\", "\\\\"),
                "size": len(raw),
                "hash": '"%s"' % digest,
                "subject": '"%s"' % SUBJECT,
            }
        )
    print("attachment:", ATTACHMENT, len(raw), "bytes, sha256", digest[:16], "…")
    print("probe script:", PROBE)


def mutate():
    with open(ATTACHMENT, "a", encoding="utf-8") as handle:
        handle.write("and one more line the sender never approved\n")
    raw = open(ATTACHMENT, "rb").read()
    print("mutated:", len(raw), "bytes, sha256 now", hashlib.sha256(raw).hexdigest()[:16], "…")


def clean():
    conn = sqlite3.connect(DB)
    removed = conn.execute(
        "delete from outbox where payload_json like ?", ("%" + SUBJECT + "%",)
    ).rowcount
    conn.commit()
    print("removed", removed, "probe row(s); outbox now", end=" ")
    print(conn.execute("select count(*) from outbox").fetchone()[0], "row(s)")
    conn.close()
    if os.path.exists(ATTACHMENT):
        os.remove(ATTACHMENT)
        print("attachment file removed")


if __name__ == "__main__":
    {"prepare": prepare, "mutate": mutate, "clean": clean}[sys.argv[1]]()
